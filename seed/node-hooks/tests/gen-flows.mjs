// S15: guard on every entry path
const guard = () => ({ id: 'guard_pay', match: { effect: ['pay'] }, pre: code('guard_pay', `
  if (ctx.args.status !== 'active') return { action: 'fail', reason: 'vendor not active' };`, { input: { status: '${{ nodes.lookup_vendor.output.status }}' } }) });
