// Generates node-hooks/flows/*.yaml: RF-1 variants in the 0.2-draft hook grammar (design sections 3 and 10), plus a few
// non-RF-1 flows and static-check negatives. The YAML files are the artefacts; this script only avoids 25 copies of RF-1 by hand.
// Run: npm run gen:flows
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { parse, stringify } from 'yaml';
import { ROOT, RF1 } from './lib.mjs';

const OUT = path.join(ROOT, 'flows');
mkdirSync(path.join(OUT, 'static'), { recursive: true });
const rf1Text = readFileSync(RF1, 'utf8');
const clone = (x) => JSON.parse(JSON.stringify(x));
const rf1 = (name) => { const d = parse(rf1Text); d.ursitoare = '0.2-draft'; d.flow = name; return d; };
const code = (id, source, extra = {}) => ({ id, kind: 'code', source: source.trim() + '\n', ...extra });
const NOOP = 'return;';
const written = [];
function emit(file, def, note) {
  const head = `# generated by tests/gen-flows.mjs${note ? `: ${note}` : ''}\n`;
  writeFileSync(path.join(OUT, file), head + stringify(def, { lineWidth: 0 }));
  written.push(file);
}
const addPre = (d, node, ...h) => { (d.nodes[node].pre ??= []).push(...h); };
const addPost = (d, node, ...h) => { (d.nodes[node].post ??= []).push(...h); };

// S02: pre mutate input on a read block
{ const d = rf1('s02-pre-mutate');
  addPre(d, 'lookup_vendor', code('canon_vendor', `
    const n = String(ctx.input.vendor_name).trim().replace(/\\s+/g, ' ').toUpperCase();
    return { action: 'continue', input: { vendor_name: n } };`));
  emit('s02-pre-mutate.yaml', d, 'S02 pre mutate input, block read'); }

// S03: post mutate output on llm.extract
{ const d = rf1('s03-post-mutate');
  addPost(d, 'extract', code('upper_currency', `
    return { action: 'continue', output: { ...ctx.output, currency: String(ctx.output.currency).toUpperCase() } };`));
  emit('s03-post-mutate.yaml', d, 'S03 post mutate output, llm.extract'); }

// S04: pre skip (cache hit) on a read block
{ const d = rf1('s04-pre-skip');
  addPre(d, 'lookup_vendor', code('vendor_cache', `
    if (ctx.input.vendor_name === 'Globex') return { action: 'skip', output: { vendor_id: 'V-GLOBEX', status: 'active', payment_terms_days: 45 } };`));
  emit('s04-pre-skip.yaml', d, 'S04 pre skip, cache hit'); }

// S05: post retry (new flow F-RET)
const fret = (name, hookSrc, max) => ({
  ursitoare: '0.2-draft', flow: name, version: '1.0.0',
  inputs: { type: 'object', properties: { query: { type: 'string' } }, required: ['query'] },
  start: 'search',
  nodes: {
    search: { kind: 'block', uses: 'kb.search@1', with: { query: '${{ inputs.query }}', top_k: 1 }, next: 'done',
      post: [code('enough_passages', hookSrc, { max_retries: max })] },
    done: { kind: 'end', status: 'completed', output: { passages: '${{ nodes.search.output.passages }}' } },
  },
});
emit('f-ret.yaml', fret('f-ret', `
  if (ctx.output.passages.length < 2) return { action: 'retry', input: { ...ctx.input, top_k: 2 }, feedback: 'need 2 passages' };`, 2), 'S05a post retry succeeds');
emit('f-ret-exhausted.yaml', fret('f-ret-exhausted', `
  return { action: 'retry', feedback: 'never satisfied' };`, 1), 'S05b post retry exhausted');

// S06: next-node redirect
const s06Hook = () => code('review_big_pay', `
  if (ctx.next && ctx.next.effect === 'pay' && ctx.args.amount > 100) return { action: 'redirect', to: 'approval' };`,
  { routes: ['approval'], input: { amount: '${{ nodes.normalize.output.amount }}' } });
{ const d = rf1('s06-next-redirect'); addPost(d, 'classify', s06Hook()); emit('s06-next-redirect.yaml', d, 'S06 post redirect on ctx.next'); }

// S07: next-node block hook
{ const d = rf1('s07-next-block-hook');
  addPost(d, 'classify', { id: 'notify_review', kind: 'block', uses: 'slack.post_message@1', when: { next: { kind: ['human.approval'] } },
    with: { channel: '#finance-review', text: 'Invoice ${{ inputs.invoice_id }} goes to review, next node: ${{ hook.next.id }}' } });
  emit('s07-next-block-hook.yaml', d, 'S07 post block hook selected by when.next'); }

// S08: previous-node logic
{ const d = rf1('s08-from-logic');
  addPre(d, 'notify_rejection', code('subject_by_origin', `
    const why = ctx.from && ctx.from.id === 'approval' ? 'rejected by reviewer' : 'auto-rejected';
    return { action: 'continue', input: { ...ctx.input, subject: ctx.input.subject + ' (' + why + ')' } };`));
  emit('s08-from-logic.yaml', d, 'S08 pre ctx.from'); }

// S09: flow selectors and onion order (also used by C1, C2-like probes and F1)
const s09 = (name) => {
  const d = rf1(name);
  d.hooks = [
    { id: 'rule_a', match: { effect: ['pay', 'send'] }, pre: code('rule_a', NOOP), post: code('rule_a', NOOP) },
    { id: 'rule_b', match: { kind: ['block'] }, pre: code('rule_b', NOOP), post: code('rule_b', NOOP) },
  ];
  addPre(d, 'pay', code('pay_pre_note', NOOP));
  addPost(d, 'pay', code('pay_post_note', NOOP));
  return d;
};
emit('s09-onion.yaml', s09('s09-onion'), 'S09 flow selectors and onion order (A=rule_a, B=rule_b)');

// S10: hooks on park nodes
const s10 = (name, timeout) => {
  const d = rf1(name);
  if (timeout) d.nodes.approval.timeout = timeout;
  addPre(d, 'approval', code('mark_large', `return { action: 'continue', input: { summary: '[large] ' + ctx.input.summary } };`));
  addPost(d, 'approval', code('approval_seen', NOOP));
  addPre(d, 'archive', code('add_source', `return { action: 'continue', input: { ...ctx.input, source: 'ursitoare' } };`));
  addPost(d, 'archive', code('archive_result_seen', `
    if (!ctx.output || !ctx.output.result || ctx.output.result.archived !== true) return { action: 'fail', reason: 'archive result missing' };`));
  return d;
};
emit('s10-park-hooks.yaml', s10('s10-park-hooks'), 'S10a hooks on human.approval and delegate');
{ const d = s10('s10b-timeout-post', 'PT5S');
  addPost(d, 'approval', code('on_timeout_seen', NOOP, { when: { outcome: ['timeout'] } }), code('on_approved_seen', NOOP, { when: { outcome: ['approved'] } }));
  emit('s10b-timeout-post.yaml', d, 'S10b post hook after the timeout exit'); }

// S11: end pre mutate
