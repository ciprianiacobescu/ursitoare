// Generates schema/ursitoare.cedarschema from the catalogue (ToolArgs union, ApproversByRole keys).
import { writeFileSync, readFileSync } from "node:fs";
import path from "node:path";
import { ROOT, loadCatalogue, unionToolArgs } from "./catalogue.ts";

export const SCHEMA_PATH = path.join(ROOT, "schema/ursitoare.cedarschema");

export function generateSchema(): string {
  const cat = loadCatalogue();
  const { attrs, untypable } = unionToolArgs(cat);
  const argLines = [...attrs.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([k, t]) => `  ${k}?: ${t}`);
  // Derived by the PEP, not a catalogue parameter: Cedar like has no host boundary (see REPORT 7.15).
  if (attrs.has("url")) argLines.push("  url_host?: String");
  const roleKeys = cat.roles.map((r) => `  "${r}"?: Set<User>`);
  const untyped = [...untypable.entries()].map(([b, ps]) => `//   ${b}: ${ps.join(", ")}`);

  return `// GENERATED by src/gen-schema.ts from shared/catalogue/blocks.v0.json. Do not edit by hand.
// Ursitoare M6 Cedar schema (empty namespace; see README for the format-v0 mapping).

entity Role;

entity User in [Role] {
  roles: Set<Role>,
  team: String,
};

entity Flow {
  owner_team: String,
  version: String,
  reviewed: Bool,
};

entity Node {
  flow: Flow,
  kind: String,
};

entity Tool {
  effect: String,
};

// One approval recorded on the run (human.approval output {decision, approver, comment} + role).
type Approval = { approver: User, role: Role };

// \`approvals\` grouped by role. Pure regrouping, no policy logic. Present only for roles
// with at least one approver. One key per catalogue role.
type ApproversByRole = {
${roleKeys.join(",\n")},
};

// Union of the non-object input properties of every catalogue block, all optional because
// Cedar records are closed and one invoke_tool context type has to cover every tool.
// Free-form object parameters cannot be typed (open records are experimental) and are NOT visible to policy:
${untyped.join("\n")}
type ToolArgs = {
${argLines.join(",\n")},
};

type LlmArgs = {
  model_profile?: String,
  tools?: Set<String>,
};

type FlowCapabilities = {
  reads_untrusted: Bool,
  reads_private: Bool,
  has_send_or_pay: Bool,
};

action invoke_tool appliesTo {
  principal: User,
  resource: Node,
  context: {
    tool: Tool,
    args: ToolArgs,
    taint: Set<String>,
    run_initiator: User,
    approvals: Set<Approval>,
    approvers_by_role: ApproversByRole,
  },
};

action invoke_llm appliesTo {
  principal: User,
  resource: Node,
  context: {
    args: LlmArgs,
    taint: Set<String>,
    run_initiator: User,
  },
};

action approve_task appliesTo {
  principal: User,
  resource: Node,
  context: {
    run_initiator: User,
    taint: Set<String>,
  },
};

action activate_flow appliesTo {
  principal: User,
  resource: Flow,
  context: {
    flow_capabilities: FlowCapabilities,
  },
};

// Addition to the required list: "finance-clerk may start runs" needs an action.
action start_run appliesTo {
  principal: User,
  resource: Flow,
  context: {},
};

action edit_flow appliesTo {
  principal: User,
  resource: Flow,
  context: {},
};
`;
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  const text = generateSchema();
  if (process.argv.includes("--check")) {
    const cur = readFileSync(SCHEMA_PATH, "utf8");
    if (cur !== text) { console.error("schema drift: re-run npm run gen-schema"); process.exit(1); }
    console.log("schema up to date");
  } else {
    writeFileSync(SCHEMA_PATH, text);
    console.log(`wrote ${SCHEMA_PATH} (${text.length} bytes)`);
  }
}
