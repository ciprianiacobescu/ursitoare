function names(group?: HookFlowGroup): string[] {
  let result: string[] | undefined;
  assert.doesNotThrow(() => {
    result = hookFlowNames(group);
  });
  assert.ok(result !== undefined);
  return result;
}

function pathOf(name: string): string {
  let result: string | undefined;
  assert.doesNotThrow(() => {
    result = hookFlowPath(name);
  });
  assert.ok(result !== undefined);
  return result;
}

function textOf(name: string): string {
  let result: string | undefined;
  assert.doesNotThrow(() => {
    result = readHookFlowText(name);
  });
  assert.ok(result !== undefined);
  return result;
}

function titleOf(name: string): string {
  let result: string | undefined;
  assert.doesNotThrow(() => {
    result = hookFlowTitle(name);
  });
  assert.ok(result !== undefined);
  return result;
}

function loaded(name: string): Flow {
  let result: Flow | undefined;
  assert.doesNotThrow(() => {
    result = loadHookFlow(name);
  });
  assert.ok(result !== undefined);
  return result;
}

function expectUnknownFlow(call: () => unknown, label: string): void {
  assert.throws(
    call,
    (error: unknown) => {
      assert.ok(
        error instanceof CatalogueDataError,
        `${label}: expected CatalogueDataError, got ${String(error)}`,
      );
      assert.equal(error.code, "CATALOGUE_UNKNOWN_FLOW", label);
      return true;
    },
    label,
  );
}

test("C-c44c4520 The hook flows are listed titled and readable", () => {
  assert.deepEqual(names("scenario"), SCENARIO_NAMES);
  assert.deepEqual(names("static"), STATIC_NAMES);
  assert.deepEqual(names(), ALL_NAMES);

  assert.equal(titleOf("n-block"), "H_BLOCK: missing required input");
  assert.equal(
    titleOf("s09-onion"),
    "S09 flow selectors and onion order (A=rule_a, B=rule_b)",
  );
  assert.equal(
    titleOf("x3-gate-bypass"),
    "X3: a declared route can skip a human gate upstream of it",
  );

  const effText = textOf("f-eff");
  assert.ok(
    effText.startsWith(
      "# generated by tests/gen-flows.mjs: C6 retry on an effect node\n",
    ),
    effText.slice(0, 80),
  );

  assert.equal(
    pathOf("n-block").endsWith("/test/support/hook-flows/flows/static/n-block.yaml"),
    true,
    pathOf("n-block"),
  );
  assert.equal(
    pathOf("f-eff").endsWith("/test/support/hook-flows/flows/f-eff.yaml"),
    true,
    pathOf("f-eff"),
  );

  for (const name of ALL_NAMES) {
    assert.equal(existsSync(pathOf(name)), true, name);
  }

  const eff = loaded("f-eff");
  assert.equal(eff.flow, "f-eff");
  assert.equal(eff.ursitoare, "0.2-draft");
  assert.equal(eff.start, "send");
  assert.deepEqual(Object.keys(eff.nodes).sort(), ["done", "send"]);

  const send = eff.nodes["send"];
  assert.ok(send, "f-eff has a send node");
  const post = send.post;
  assert.ok(Array.isArray(post) && post.length > 0, "f-eff send has a post hook");
  assert.equal(
    (post[0] as { allow_effect_retry?: unknown }).allow_effect_retry,
    true,
  );
});

test("C-ff311e59 Unknown hook-flow names are refused", () => {
  const badNames = [
    "",
    "ghost",
    "n-block.yaml",
    "static/n-block",
    "../index",
    "__proto__",
    "F-EFF",
  ];

  for (const name of badNames) {
    expectUnknownFlow(() => hookFlowPath(name), `hookFlowPath ${name}`);
    expectUnknownFlow(() => readHookFlowText(name), `readHookFlowText ${name}`);
    expectUnknownFlow(() => hookFlowTitle(name), `hookFlowTitle ${name}`);
    expectUnknownFlow(() => loadHookFlow(name), `loadHookFlow ${name}`);
  }
});

test("C-6fca27d8 All 48 shipped flows resolve", () => {
  const catalogue = loadTestCatalogue();

  const testFlows = new Map<string, Flow>();
  for (const name of TEST_FLOW_NAMES) {
    let flow: Flow | undefined;
    assert.doesNotThrow(() => {
      flow = loadTestFlow(name);
    });
    assert.ok(flow !== undefined, name);
    testFlows.set(name, flow);
  }

  const hookNames = names();
  const hookFlows = new Map<string, Flow>();
  for (const name of hookNames) {
    let flow: Flow | undefined;
    assert.doesNotThrow(() => {
      flow = loadHookFlow(name);
    });
    assert.ok(flow !== undefined, name);
    assert.equal(flow.flow, name, name);
    hookFlows.set(name, flow);
  }

  const allFlows = new Map<string, Flow>([...testFlows, ...hookFlows]);
  assert.equal(allFlows.size, 48);

  for (const [label, flow] of allFlows) {
    assert.deepEqual(unresolvedReferences(flow, catalogue), [], label);
    for (const [id, node] of Object.entries(flow.nodes)) {
      if (node.kind === "human.approval") {
        assert.equal(
          (node as { assignee_role?: unknown }).assignee_role,
          "approver",
          `${label} ${id}`,
        );
      }
    }
  }

  const withoutApproval = hookNames.filter((name) => {
    const flow = hookFlows.get(name);
    assert.ok(flow !== undefined, name);
    return !Object.values(flow.nodes).some((node) => node.kind === "human.approval");
  });

  assert.deepEqual(withoutApproval, ["f-eff", "f-ret", "f-ret-exhausted"]);
});
