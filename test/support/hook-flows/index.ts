// The hook flows: names, paths, titles, text and loading (design Decisions 6 and 7).

import { readdirSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import type { Flow } from "../../../src/authoring/index.ts";
import { CatalogueDataError } from "../catalogue/errors.ts";
import { parseCatalogueFlow } from "../catalogue/flows.ts";

export type HookFlowGroup = "scenario" | "static";

const TITLE_PREFIX = "# generated by tests/gen-flows.mjs: ";

function groupDirectory(group: HookFlowGroup): string {
  const url = group === "static" ? "./flows/static/" : "./flows/";
  return fileURLToPath(new URL(url, import.meta.url));
}

function listGroup(group: HookFlowGroup): string[] {
  return readdirSync(groupDirectory(group))
    .filter((file) => file.endsWith(".yaml"))
    .map((file) => file.slice(0, -".yaml".length));
}

function byCodeUnit(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

export function hookFlowNames(group?: HookFlowGroup): string[] {
  const names = group === undefined ? [...listGroup("scenario"), ...listGroup("static")] : listGroup(group);
  return names.sort(byCodeUnit);
}

export function hookFlowPath(name: string): string {
  if (typeof name === "string") {
    for (const group of ["scenario", "static"] as const) {
      if (listGroup(group).includes(name)) {
        return `${groupDirectory(group)}${name}.yaml`;
      }
    }
  }
  throw new CatalogueDataError("CATALOGUE_UNKNOWN_FLOW", `unknown hook flow: ${String(name)}`);
}

export function readHookFlowText(name: string): string {
  const path = hookFlowPath(name);
  try {
    return readFileSync(path, "utf8");
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    throw new CatalogueDataError("CATALOGUE_READ", `cannot read ${path}: ${message}`);
  }
}

export function hookFlowTitle(name: string): string {
  const first = readHookFlowText(name).split("\n", 1)[0] ?? "";
  if (!first.startsWith(TITLE_PREFIX)) {
    throw new CatalogueDataError("CATALOGUE_INVALID", `${name}: the first line has no title prefix`);
  }
  return first.slice(TITLE_PREFIX.length);
}

export function loadHookFlow(name: string): Flow {
  return parseCatalogueFlow(readHookFlowText(name), name);
}
